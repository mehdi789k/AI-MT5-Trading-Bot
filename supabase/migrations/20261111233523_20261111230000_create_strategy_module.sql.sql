-- 4. Add strategy columns to symbol_config (no data loss)
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'symbol_config' AND column_name = 'strategy_id') THEN
    ALTER TABLE symbol_config ADD COLUMN strategy_id uuid REFERENCES strategies(id) ON DELETE SET NULL;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'symbol_config' AND column_name = 'strategy_mode') THEN
    ALTER TABLE symbol_config ADD COLUMN strategy_mode text NOT NULL DEFAULT 'ai';
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.table_constraints WHERE constraint_name = 'symbol_config_strategy_mode_ck' AND table_name = 'symbol_config') THEN
    ALTER TABLE symbol_config ADD CONSTRAINT symbol_config_strategy_mode_ck CHECK (strategy_mode IN ('ai','strategy','both'));
  END IF;
END $$;

