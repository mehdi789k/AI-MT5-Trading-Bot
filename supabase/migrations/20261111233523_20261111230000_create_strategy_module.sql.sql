DROP POLICY IF EXISTS "anon_insert_signals" ON strategy_signals;
CREATE POLICY "anon_insert_signals" ON strategy_signals FOR INSERT TO anon, authenticated WITH CHECK (true);
DROP POLICY IF EXISTS "anon_delete_signals" ON strategy_signals;
