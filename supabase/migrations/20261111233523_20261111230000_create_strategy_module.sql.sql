/*
# Strategy Module — Custom Python Strategies, Backtests & Signals

## Overview
Adds a complete strategy management system to the trading bot. Users can write,
upload, edit, and download Python trading strategies from the dashboard. Each
strategy generates buy/sell/neutral signals based on custom logic. Strategies
can be backtested against MT5 historical data and assigned to symbols.

Single-user app (no sign-in). All policies target anon, authenticated with
USING(true) since data is intentionally shared.

## New Tables
1. `strategies` — stores user-created Python strategy scripts
2. `strategy_backtest_results` — results of backtest runs
3. `strategy_signals` — live signals generated by active strategies

## Modified Tables
- `symbol_config`: add strategy_id and strategy_mode columns

## Security
- RLS enabled on all new tables; grants to anon, authenticated; policies USING(true).
*/

-- 1. strategies
CREATE TABLE IF NOT EXISTS strategies (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  description text DEFAULT '',
  code text NOT NULL DEFAULT '',
  is_active boolean NOT NULL DEFAULT false,
  version integer NOT NULL DEFAULT 1,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);
ALTER TABLE strategies ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON strategies TO anon, authenticated;
DROP POLICY IF EXISTS "anon_select_strategies" ON strategies;
CREATE POLICY "anon_select_strategies" ON strategies FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "anon_insert_strategies" ON strategies;
CREATE POLICY "anon_insert_strategies" ON strategies FOR INSERT TO anon, authenticated WITH CHECK (true);
DROP POLICY IF EXISTS "anon_update_strategies" ON strategies;
CREATE POLICY "anon_update_strategies" ON strategies FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "anon_delete_strategies" ON strategies;
CREATE POLICY "anon_delete_strategies" ON strategies FOR DELETE TO anon, authenticated USING (true);

-- 2. strategy_backtest_results
CREATE TABLE IF NOT EXISTS strategy_backtest_results (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  strategy_id uuid REFERENCES strategies(id) ON DELETE CASCADE,
  symbol text NOT NULL,
  timeframe text NOT NULL,
  from_date date,
  to_date date,
  initial_capital numeric(12,2) DEFAULT 10000,
  net_profit numeric(12,2) DEFAULT 0,
  total_trades integer DEFAULT 0,
  wins integer DEFAULT 0,
  losses integer DEFAULT 0,
  win_rate numeric(5,2) DEFAULT 0,
  max_drawdown numeric(5,2) DEFAULT 0,
  profit_factor numeric(8,2) DEFAULT 0,
  equity_curve jsonb DEFAULT '[]',
  trades_detail jsonb DEFAULT '[]',
  status text NOT NULL DEFAULT 'completed',
  error_message text,
  created_at timestamptz DEFAULT now()
);
ALTER TABLE strategy_backtest_results ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON strategy_backtest_results TO anon, authenticated;
DROP POLICY IF EXISTS "anon_select_bt_results" ON strategy_backtest_results;
CREATE POLICY "anon_select_bt_results" ON strategy_backtest_results FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "anon_insert_bt_results" ON strategy_backtest_results;
CREATE POLICY "anon_insert_bt_results" ON strategy_backtest_results FOR INSERT TO anon, authenticated WITH CHECK (true);
DROP POLICY IF EXISTS "anon_update_bt_results" ON strategy_backtest_results;
CREATE POLICY "anon_update_bt_results" ON strategy_backtest_results FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "anon_delete_bt_results" ON strategy_backtest_results;
CREATE POLICY "anon_delete_bt_results" ON strategy_backtest_results FOR DELETE TO anon, authenticated USING (true);
CREATE INDEX IF NOT EXISTS idx_bt_results_strategy ON strategy_backtest_results(strategy_id);
CREATE INDEX IF NOT EXISTS idx_bt_results_created ON strategy_backtest_results(created_at DESC);

-- 3. strategy_signals
CREATE TABLE IF NOT EXISTS strategy_signals (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  strategy_id uuid REFERENCES strategies(id) ON DELETE CASCADE,
  symbol text NOT NULL,
  direction text NOT NULL,
  confidence numeric(5,2) DEFAULT 0,
  reason text DEFAULT '',
  created_at timestamptz DEFAULT now(),
  CONSTRAINT ss_dir_ck CHECK (direction IN ('buy','sell','neutral'))
);
ALTER TABLE strategy_signals ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, DELETE ON strategy_signals TO anon, authenticated;
DROP POLICY IF EXISTS "anon_select_signals" ON strategy_signals;
